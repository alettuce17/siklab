create extension if not exists pgcrypto with schema extensions;

create table if not exists public.school_years (
    year_id bigint generated by default as identity primary key,
    label varchar(20) not null unique,
    is_active boolean not null default false,
    created_at timestamptz not null default now()
);

create table if not exists public.student (
    student_id bigint generated by default as identity primary key,
    lrn varchar(12) unique,
    first_name varchar(50) not null,
    last_name varchar(50) not null,
    section varchar(50) default 'Grade 3 - Mabini',
    grade_level integer not null default 3,
    school_year_id bigint references public.school_years(year_id) on delete set null,
    created_at timestamptz not null default now(),
    constraint student_lrn_12_digits check (lrn is null or lrn ~ '^[0-9]{12}$')
);

create table if not exists public.custom_game_module (
    game_id bigint generated by default as identity primary key,
    quarter integer not null default 1 check (quarter between 1 and 4),
    game_name varchar(150) not null,
    file_path varchar(255) not null,
    is_editable boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists public.custom_question (
    question_id bigint generated by default as identity primary key,
    game_module varchar(50) not null,
    prompt text not null,
    correct_ans integer not null check (correct_ans between 0 and 4),
    time_limit integer not null default 10 check (time_limit > 0),
    image_url text,
    created_at timestamptz not null default now()
);

create table if not exists public.game_settings (
    setting_id bigint generated by default as identity primary key,
    game_module varchar(50) not null unique,
    settings_json jsonb not null default '{}'::jsonb,
    updated_at timestamptz not null default now()
);

create table if not exists public.lesson_modules (
    module_id bigint generated by default as identity primary key,
    week_id integer not null,
    school_year_id bigint not null references public.school_years(year_id) on delete cascade,
    label varchar(50),
    title varchar(150) not null,
    subtitle varchar(255),
    icon varchar(50) default 'fa-book-open',
    color varchar(50) default 'blue',
    completion_type varchar(20) default 'quiz' check (completion_type in ('quiz','view')),
    lesson_json jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (school_year_id, week_id)
);

create table if not exists public.student_group_set (
    set_id bigint generated by default as identity primary key,
    school_year_id bigint not null references public.school_years(year_id) on delete cascade,
    set_label varchar(20) not null,
    group_data jsonb not null default '[]'::jsonb,
    updated_at timestamptz not null default now(),
    unique (school_year_id, set_label)
);

create table if not exists public.student_progress (
    progress_id bigint generated by default as identity primary key,
    student_name varchar(100) not null unique,
    stars integer not null default 0,
    unlocked_weeks jsonb not null default '[1]'::jsonb,
    updated_at timestamptz not null default now()
);

create table if not exists public.game_type (
    game_type_id bigint generated by default as identity primary key,
    name varchar(100) not null,
    mechanics_config jsonb,
    requires_questions boolean default true
);

create table if not exists public.topic (
    topic_id bigint generated by default as identity primary key,
    teacher_user_id uuid references auth.users(id) on delete set null,
    week_number integer not null,
    day_number integer not null,
    title varchar(150)
);

create table if not exists public.game_session (
    session_id bigint generated by default as identity primary key,
    game_type_id bigint references public.game_type(game_type_id) on delete set null,
    topic_id bigint references public.topic(topic_id) on delete set null,
    played_at timestamptz not null default now()
);

create table if not exists public.question (
    question_id bigint generated by default as identity primary key,
    topic_id bigint references public.topic(topic_id) on delete cascade,
    game_type_id bigint references public.game_type(game_type_id) on delete set null,
    prompt text not null,
    asset_url text,
    time_limit_sec integer default 10
);

create table if not exists public.question_option (
    option_id bigint generated by default as identity primary key,
    question_id bigint references public.question(question_id) on delete cascade,
    option_text varchar(100) not null,
    is_correct boolean default false,
    hardware_button_map integer not null
);

create table if not exists public.iot_device (
    mac_address varchar(32) primary key,
    assigned_player varchar(20),
    status varchar(20) default 'Active'
);

create table if not exists public.player_score (
    score_id bigint generated by default as identity primary key,
    session_id bigint references public.game_session(session_id) on delete cascade,
    student_id bigint references public.student(student_id) on delete cascade,
    mac_address varchar(32) references public.iot_device(mac_address) on delete set null,
    final_score integer default 0,
    highest_combo integer default 1,
    correct_answers integer default 0,
    wrong_answers integer default 0,
    avg_reaction_time_ms integer,
    custom_game_data jsonb,
    created_at timestamptz not null default now()
);

create table if not exists public.player_response (
    response_id bigint generated by default as identity primary key,
    session_id bigint references public.game_session(session_id) on delete cascade,
    student_id bigint references public.student(student_id) on delete cascade,
    question_id bigint references public.question(question_id) on delete cascade,
    selected_option_id bigint references public.question_option(option_id) on delete set null,
    is_correct boolean,
    reaction_time_ms integer,
    created_at timestamptz not null default now()
);

create table if not exists public.controller_devices (
    device_id text primary key,
    assigned_player text not null check (assigned_player in ('player1','player2')),
    device_token_hash text not null,
    enabled boolean not null default true,
    last_state text check (last_state is null or last_state ~ '^[01]{9}$'),
    last_seen timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create unique index if not exists uq_controller_active_player
    on public.controller_devices (assigned_player)
    where enabled = true;

