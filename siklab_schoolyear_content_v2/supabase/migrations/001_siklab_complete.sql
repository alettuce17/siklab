-- Safe lesson reorder
create or replace function public.reorder_lessons(
    p_school_year_id bigint,
    p_module_ids bigint[]
)
returns void
language plpgsql
security invoker
set search_path = public
as $$
declare
    v_module_id bigint;
    v_position integer := 1;
begin
    if auth.uid() is null then raise exception 'Authentication required'; end if;

    foreach v_module_id in array p_module_ids loop
        update public.lesson_modules
        set week_id = -100000 - v_position, updated_at = now()
        where module_id = v_module_id and school_year_id = p_school_year_id;
        if not found then
            raise exception 'Lesson % does not belong to school year %', v_module_id, p_school_year_id;
        end if;
        v_position := v_position + 1;
    end loop;

    v_position := 1;
    foreach v_module_id in array p_module_ids loop
        update public.lesson_modules
        set week_id = v_position,
            lesson_json = jsonb_set(coalesce(lesson_json,'{}'::jsonb), '{week_id}', to_jsonb(v_position), true),
            updated_at = now()
        where module_id = v_module_id and school_year_id = p_school_year_id;
        v_position := v_position + 1;
    end loop;
end;
$$;
grant execute on function public.reorder_lessons(bigint,bigint[]) to authenticated;

-- Controller provisioning
create or replace function public.provision_controller(p_device_id text, p_player text)
returns table(device_id text, assigned_player text, device_token text)
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
    v_device_id text := upper(trim(p_device_id));
    v_token text := encode(extensions.gen_random_bytes(32), 'hex');
    v_hash text := encode(extensions.digest(v_token, 'sha256'), 'hex');
begin
    if v_device_id !~ '^[A-F0-9]{6,32}$' then raise exception 'Invalid device id'; end if;
    if p_player not in ('player1','player2') then raise exception 'Player must be player1 or player2'; end if;

    update public.controller_devices
       set enabled = false, updated_at = now()
     where assigned_player = p_player
       and device_id <> v_device_id
       and enabled = true;

    insert into public.controller_devices(device_id,assigned_player,device_token_hash,enabled,updated_at)
    values(v_device_id,p_player,v_hash,true,now())
    on conflict(device_id) do update
       set assigned_player=excluded.assigned_player,
           device_token_hash=excluded.device_token_hash,
           enabled=true,
           updated_at=now();

    return query select v_device_id,p_player,v_token;
end;
$$;
revoke all on function public.provision_controller(text,text) from public;
revoke all on function public.provision_controller(text,text) from anon;
revoke all on function public.provision_controller(text,text) from authenticated;

create or replace function public.disable_controller(p_device_id text)
returns void
language sql
security definer
set search_path = public
as $$
    update public.controller_devices
    set enabled=false, updated_at=now()
    where device_id=upper(trim(p_device_id));
$$;
revoke all on function public.disable_controller(text) from public;
revoke all on function public.disable_controller(text) from anon;
revoke all on function public.disable_controller(text) from authenticated;

